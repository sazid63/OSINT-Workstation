"""Investigation storage layout.

Data lives outside the source tree by default so an installed copy does not
write into its own package directory and reports survive an upgrade. Override
with the OSINT_DATA_DIR environment variable. Investigations from the older
repo-local `investigations/` folder are still readable.
"""
import datetime
import json
import os
import re

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LEGACY_INV = os.path.join(BASE, 'investigations')


def data_dir() -> str:
    env = os.environ.get('OSINT_DATA_DIR')
    if env:
        return os.path.abspath(os.path.expanduser(env))
    local = os.environ.get('LOCALAPPDATA')
    if local:
        return os.path.join(local, 'OSINT-Workstation')
    xdg = os.environ.get('XDG_DATA_HOME')
    if xdg:
        return os.path.join(xdg, 'osint-workstation')
    return os.path.join(os.path.expanduser('~'), '.osint-workstation')


INV = os.path.join(data_dir(), 'investigations')

SUBDIRS = ['metadata', 'raw', 'normalized', 'sources', 'screenshots',
           'graph', 'logs', 'reports']

# Conservative: ids are generated by safe_name() below (letters, digits, _.-).
_ID_RE = re.compile(r'^[A-Za-z0-9][A-Za-z0-9_.\-]{0,119}$')


def validate_inv_id(inv_id: str) -> str:
    """Reject anything that is not a plain identifier.

    Investigation ids reach the filesystem directly, so an unvalidated value is
    a path-traversal primitive (`osint report ../../secret`).
    """
    v = (inv_id or '').strip()
    if not _ID_RE.match(v) or '..' in v:
        raise ValueError(
            f'invalid investigation id {inv_id!r}: expected letters, digits, '
            f"'.', '_' or '-' and no path separators")
    return v


def safe_name(target: str) -> str:
    return re.sub(r'[^A-Za-z0-9_.-]+', '_', target.strip())[:80]


def inv_path(inv_id: str) -> str:
    """Return the directory for an investigation, validating the id first."""
    v = validate_inv_id(inv_id)
    for root in (INV, LEGACY_INV):
        candidate = os.path.join(root, v)
        if os.path.isdir(candidate):
            return candidate
    return os.path.join(INV, v)


def create_investigation(target: str, target_type: str, plan: list, **extra) -> dict:
    day = datetime.datetime.now().strftime('%Y-%m-%d')
    base = f"{day}_{safe_name(target)}"
    path = os.path.join(INV, base)
    # never overwrite: suffix _2, _3...
    n, final = 1, path
    while os.path.exists(final):
        n += 1
        final = f"{path}_{n}"
    for sub in SUBDIRS:
        os.makedirs(os.path.join(final, sub), exist_ok=True)
    inv_id = os.path.basename(final)
    meta = {
        'id': inv_id, 'target': target, 'target_type': target_type,
        'plan': plan, 'created_utc': datetime.datetime.now(datetime.timezone.utc).isoformat(),
        'path': final,
    }
    meta.update(extra)
    with open(os.path.join(final, 'metadata', 'meta.json'), 'w', encoding='utf-8') as f:
        json.dump(meta, f, indent=2)
    return meta


def list_investigations() -> list:
    """Ids of stored investigations, newest last (name order is date-first)."""
    ids = []
    for root in (LEGACY_INV, INV):
        if os.path.isdir(root):
            ids.extend(sorted(d for d in os.listdir(root)
                              if os.path.isdir(os.path.join(root, d))))
    return ids


def save_raw(inv_id: str, tool: str, data) -> str:
    p = os.path.join(inv_path(inv_id), 'raw', f'{safe_name(tool)}.json')
    with open(p, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=2, default=str)
    return p
